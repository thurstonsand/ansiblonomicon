def syntax_scopes(p: Mapping[str, str]) -> dict[str, str]:
    return {scope: color for _, scopes, color in syntax_rules(p) for scope in scopes}


def hunk_toml(p: Mapping[str, str], label: str, mode: str) -> str:
    body = [f"# {GENERATED}", "[custom_theme]"]
    body += [f'{key} = "{value}"' for key, value in hunk_theme(p, label, mode).items()]
    body += ["", "[custom_theme.syntax_scopes]"]
    body += [f'"{scope}" = "{color}"' for scope, color in syntax_scopes(p).items()]
    return "\n".join(body) + "\n"


def hunk_json(p: Mapping[str, str], label: str, mode: str) -> str:
    """The theme the Omarchy Hunk extension registers as `omarchy`."""
    theme: dict[str, object] = {
        "id": "omarchy",
        **hunk_theme(p, label, mode),
        "syntaxScopes": syntax_scopes(p),
    }
    return json.dumps(theme, indent=2) + "\n"


def tm_theme(p: Mapping[str, str], label: str) -> str:
    def entry(
        name: str,
        scopes: list[str],
        foreground: str,
        background: str | None = None,
        font: str | None = None,
    ) -> str:
        settings = f"<key>foreground</key><string>{foreground}</string>"
        if background:
            settings += f"<key>background</key><string>{background}</string>"
        if font:
            settings += f"<key>fontStyle</key><string>{font}</string>"
        return (
            f"    <dict><key>name</key><string>{name}</string>"
            f"<key>scope</key><string>{', '.join(scopes)}</string>"
            f"<key>settings</key><dict>{settings}</dict></dict>"
        )

    rules = [entry(name, scopes, color) for name, scopes, color in syntax_rules(p)]
    rules += [
        entry("Heading", ["markup.heading", "entity.name.section"], p["ember"], font="bold"),
        entry("Inserted", ["markup.inserted"], p["added"], p["added_content_bg"]),
        entry("Deleted", ["markup.deleted"], p["ember"], p["removed_content_bg"]),
        entry("Changed", ["markup.changed"], p["changed"]),
        entry("Invalid", ["invalid"], p["ember"]),
    ]  # fmt: skip
    return (
        "\n".join(
            [
                '<?xml version="1.0" encoding="UTF-8"?>',
                f"<!-- {GENERATED} -->",
                '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
                '<plist version="1.0">',
                "<dict>",
                f"  <key>name</key><string>{label}</string>",
                "  <key>settings</key>",
                "  <array>",
                "    <dict><key>settings</key><dict>"
                f"<key>background</key><string>{p['bg']}</string>"
                f"<key>foreground</key><string>{p['fg']}</string>"
                f"<key>caret</key><string>{p['bright_fg']}</string>"
                f"<key>selection</key><string>{p['selection']}</string>"
                f"<key>lineHighlight</key><string>{p['panel']}</string>"
                f"<key>invisibles</key><string>{p['border']}</string>"
                "</dict></dict>",
                *rules,
                "  </array>",
                "</dict>",
                "</plist>",
            ]
        )
        + "\n"
    )


