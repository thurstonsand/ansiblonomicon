def ghostty(colors: Mapping[str, str]) -> str:
    ansi = [
        "background", "red", "green", "yellow", "blue", "magenta", "cyan", "foreground",
        "muted", "bright_red", "bright_green", "bright_yellow", "bright_blue",
        "bright_magenta", "bright_cyan", "bright_foreground",
    ]  # fmt: skip
    lines = [
        f"# {GENERATED}",
        f"background = {colors['background']}",
        f"foreground = {colors['foreground']}",
        f"cursor-color = {colors['bright_foreground']}",
        f"selection-background = {colors['selection']}",
        f"selection-foreground = {colors['bright_foreground']}",
        *(f"palette = {index}={colors[name]}" for index, name in enumerate(ansi)),
    ]
    return "\n".join(lines) + "\n"


