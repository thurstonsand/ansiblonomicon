type Palette = dict[str, str]
type Lab = tuple[float, float, float]


def _to_linear(channel: float) -> float:
    return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4


def _to_srgb(channel: float) -> float:
    channel = min(max(channel, 0.0), 1.0)
    return (
        12.92 * channel
        if channel <= 0.0031308
        else 1.055 * channel ** (1 / 2.4) - 0.055
    )


def _rgb(color: str) -> tuple[float, float, float]:
    value = color.lstrip("#")
    return (
        int(value[0:2], 16) / 255,
        int(value[2:4], 16) / 255,
        int(value[4:6], 16) / 255,
    )


def _hex(rgb: tuple[float, float, float]) -> str:
    return "#" + "".join(f"{round(channel * 255):02x}" for channel in rgb)


def _oklab(color: str) -> Lab:
    r, g, b = (_to_linear(channel) for channel in _rgb(color))
    long = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    medium = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    short = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    return (
        0.2104542553 * long + 0.7936177850 * medium - 0.0040720468 * short,
        1.9779984951 * long - 2.4285922050 * medium + 0.4505937099 * short,
        0.0259040371 * long + 0.7827717662 * medium - 0.8086757660 * short,
    )


def _linear_rgb(lab: Lab) -> tuple[float, float, float]:
    lightness, a, b = lab
    long = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    medium = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    short = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (
        4.0767416621 * long - 3.3077115913 * medium + 0.2309699292 * short,
        -1.2684380046 * long + 2.6097574011 * medium - 0.3413193965 * short,
        -0.0041960863 * long - 0.7034186147 * medium + 1.7076147010 * short,
    )


def _from_oklab(lab: Lab) -> str:
    # Clipping channels independently skews hue (dark gold turns red-brown), so
    # shed chroma until the color fits sRGB and the hue survives the mirror.
    lightness, a, b = lab
    low, high = 0.0, 1.0
    if not all(0.0 <= channel <= 1.0 for channel in _linear_rgb(lab)):
        for _ in range(32):
            scale = (low + high) / 2
            if all(
                0.0 <= channel <= 1.0
                for channel in _linear_rgb((lightness, a * scale, b * scale))
            ):
                low = scale
            else:
                high = scale
        lab = (lightness, a * low, b * low)
    r, g, b = _linear_rgb(lab)
    return _hex((_to_srgb(r), _to_srgb(g), _to_srgb(b)))


def mirror(palette: Mapping[str, str], background: str, foreground: str) -> Palette:
    """Map background to light lightness, foreground to dark, keeping hue and chroma."""
    dark_bg = _oklab(background)[0]
    dark_fg = _oklab(foreground)[0]
    mirrored: Palette = {}
    for name, color in palette.items():
        lightness, a, b = _oklab(color)
        position = (lightness - dark_bg) / (dark_fg - dark_bg)
        target = LIGHT_BACKGROUND_L + position * (
            LIGHT_FOREGROUND_L - LIGHT_BACKGROUND_L
        )
        mirrored[name] = _from_oklab((target, a, b))
    return mirrored


def mix(start: str, end: str, amount: float) -> str:
    """Blend in sRGB the way Omarchy's `{{ mix }}` template helper does."""
    (r1, g1, b1), (r2, g2, b2) = _rgb(start), _rgb(end)
    return _hex(
        (
            r1 * (1 - amount) + r2 * amount,
            g1 * (1 - amount) + g2 * amount,
            b1 * (1 - amount) + b2 * amount,
        )
    )


def alpha(color: str, opacity: float) -> str:
    """Append an alpha byte, which works on a hex value and on an Omarchy placeholder alike."""
    return f"{color}{round(opacity * 255):02x}"


class Colors(Protocol):
    """Looks up and blends Omarchy `colors.toml` keys."""

    def __getitem__(self, key: str) -> str: ...
    def mix(self, start: str, end: str, amount: float) -> str: ...


class Swatches:
    """One concrete palette's hex values."""

    def __init__(self, colors: Mapping[str, str]) -> None:
        self.colors = colors

    def __getitem__(self, key: str) -> str:
        return self.colors[key]

    def mix(self, start: str, end: str, amount: float) -> str:
        return mix(self.colors[start], self.colors[end], amount)


class Placeholders:
    """Omarchy template placeholders, resolved per theme by omarchy-theme-set-templates."""

    def __getitem__(self, key: str) -> str:
        return f"{{{{ {key} }}}}"

    def mix(self, start: str, end: str, amount: float) -> str:
        return f"{{{{ mix {start} {end} {round(amount * 100)}% }}}}"


